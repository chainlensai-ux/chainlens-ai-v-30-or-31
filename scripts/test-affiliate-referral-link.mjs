// TESTS — Affiliate self-serve referral link + tracking.
//
// Covers the request: "once someone joins the affiliate program they should automatically get their
// own referral link that they can copy and start sharing immediately... sign up → get their link →
// start promoting → track their referrals/commissions."
//
// Two layers:
//  1. Real unit tests of lib/affiliate/referral.ts — the link builder and the code validation /
//     cookie-reading functions the whole attribution chain depends on.
//  2. Static source checks over the routes and pages, matching this codebase's established pattern
//     for asserting behavior embedded in Next.js route handlers and client components
//     (see scripts/test-robinhood-liquidity-safety-chain.mjs).

import assert from 'node:assert/strict'
import { readFileSync } from 'node:fs'
import {
  AFFILIATE_SITE_ORIGIN,
  buildAffiliateReferralLink,
  isValidReferralCode,
  normalizeReferralCode,
  readReferralCodeFromCookie,
} from '../lib/affiliate/referral.ts'

let passed = 0
function check(label, condition) { assert.ok(condition, label); passed++ }

// ─── 1. The link builder ────────────────────────────────────────────────────────────────────────
{
  const link = buildAffiliateReferralLink('cl1a2b3c4d')
  check('a referral link points at the pricing page, where a referred visitor converts', link === `${AFFILIATE_SITE_ORIGIN}/pricing?ref=cl1a2b3c4d`)
  check('the link carries the code in the ?ref= parameter AffiliateRefCapture actually reads', /[?&]ref=cl1a2b3c4d(?:$|&)/.test(link))
  check('the origin is absolute, so a copied link works when pasted anywhere off-site', link.startsWith('https://'))
  check('codes are normalized into the link, so a pasted upper-case code still resolves', buildAffiliateReferralLink('CL1A2B3C4D') === buildAffiliateReferralLink('cl1a2b3c4d'))
  check('the built link round-trips through the validator the checkout path uses', isValidReferralCode(new URL(link).searchParams.get('ref')))
}

// ─── 2. Codes generated by the apply route are actually usable end to end ───────────────────────
{
  // app/api/affiliate/apply/route.ts builds 'cl' + randomBytes(4).toString('hex'), and on a unique
  // collision appends '-' + randomBytes(2).toString('hex'). BOTH shapes must survive validation —
  // if the collision variant failed isValidReferralCode, that affiliate's link would be generated,
  // shown, and then silently ignored at checkout, and they would never know why.
  const primary = 'cl' + '1a2b3c4d'
  const collision = primary + '-5e6f'
  check('the primary generated code shape is a valid referral code', isValidReferralCode(primary))
  check('the collision-retry code shape (with its hyphen suffix) is ALSO valid, so those links track too', isValidReferralCode(collision))
  check('both shapes produce a working link', buildAffiliateReferralLink(collision).endsWith(`?ref=${collision}`))
  check('a code is never mangled by normalization', normalizeReferralCode(collision) === collision)
}

// ─── 3. Attribution cookie round-trip — the link is worthless if this breaks ────────────────────
{
  const code = 'cl1a2b3c4d'
  check('the capture cookie is read back as the same code the link carried', readReferralCodeFromCookie(`chainlens_affiliate_ref=${code}`) === code)
  check('the cookie is still found when other cookies precede it', readReferralCodeFromCookie(`sb-access-token=xyz; chainlens_affiliate_ref=${code}; other=1`) === code)
  check('an absent cookie yields null, never a fabricated code', readReferralCodeFromCookie('other=1') === null)
  check('a malformed cookie value is rejected rather than trusted', readReferralCodeFromCookie('chainlens_affiliate_ref=not a valid code!!') === null)
}

// ─── 4. Self-serve endpoint: authorization and honesty ──────────────────────────────────────────
{
  const me = readFileSync(new URL('../app/api/affiliate/me/route.ts', import.meta.url), 'utf8')
  check('identity comes from a verified bearer token, not a client-supplied email', me.includes('anon.auth.getUser(token)'))
  check('the affiliate row is looked up by the email taken off the verified user object', /userData\.user\.email/.test(me) && /\.ilike\('email', email\)/.test(me))
  check('an unauthenticated request is rejected with 401, never served a row', /status: 401/.test(me))
  // Scoped to real code, not prose: the file's own header names payout_wallet when explaining why
  // it is withheld, so a whole-file match would fail on the documentation of the guarantee itself.
  const meCode = me.split('\n').filter((l) => !l.trim().startsWith('//')).join('\n')
  check('payout_wallet is never selected from the database, so a payout destination cannot leak', !/payout_wallet/.test(meCode))
  check('every stats query is scoped to the caller\'s own affiliate id', me.split('\n').filter((l) => l.includes('.eq(')).every((l) => /aff\.id/.test(l)))
  check('linkIsLive mirrors the real approved-only gate in the checkout path', me.includes("linkIsLive: aff.status === 'approved'"))
  check('a failed count reports null (unknown), never a fabricated 0 that would read as "you earned nothing"', me.includes('referredUsersRes.error ? null') && me.includes('paymentsRes.error ? null'))
  check('a failed commission read is surfaced as unavailable rather than as zero earnings', me.includes('unavailable: true'))
  check('not being an affiliate is an ordinary response, not an error status', me.includes('isAffiliate: false'))
  check('the endpoint is rate limited', me.includes('createRateLimiter'))
  check('the link is built with the shared helper, never a second hardcoded origin', me.includes('buildAffiliateReferralLink') && !me.includes('chainlensai.app'))
}

// ─── 5. The link is copyable and no longer lost after one render ────────────────────────────────
{
  const applyPage = readFileSync(new URL('../app/affiliate/page.tsx', import.meta.url), 'utf8')
  const dash = readFileSync(new URL('../app/affiliate/dashboard/page.tsx', import.meta.url), 'utf8')

  check('the apply success box offers a copy button, not just plain text', /Copy/.test(applyPage) && applyPage.includes('clipboard.writeText'))
  check('the apply success box builds its link with the shared helper', applyPage.includes('buildAffiliateReferralLink'))
  check('the old hardcoded success-box origin is gone', !applyPage.includes('https://www.chainlensai.app/pricing?ref='))
  check('applying now routes the user to a durable dashboard, so the link is recoverable', applyPage.includes('/affiliate/dashboard'))

  check('the dashboard has its own copy control', dash.includes('clipboard.writeText') && /Copy link/.test(dash))
  check('the dashboard reads the self-serve endpoint', dash.includes("'/api/affiliate/me'"))
  check('the dashboard sends the session bearer token', dash.includes('Authorization: `Bearer ${token}`'))
  check('a signed-out visitor is told to sign in rather than shown an error', dash.includes('Sign in to see your link'))
  check('a signed-in non-affiliate gets a join CTA, not a failure', dash.includes('No affiliate account on this email'))
  check('the dashboard states plainly when a pending link is NOT yet tracking', /not tracking yet/i.test(dash))
  check('the pending warning is driven by the real linkIsLive flag, not assumed', dash.includes('!d.linkIsLive'))
  check('an unavailable figure renders as "Unavailable", never as a zero', dash.includes("'Unavailable'"))
}

console.log(`test-affiliate-referral-link.mjs: all ${passed} assertions passed`)
